"""Write the text outputs from metrics: RESULTS.md, THESIS.md and the README block.

Prose lives in templates (ledger/thesis_template.md, and README.md between
its RESULTS markers). Numbers are never typed by hand: every `{{name}}` in a
template is filled from `facts()`, and an unknown name is an error.
"""
import os
import re

from . import claims

HERE = os.path.dirname(os.path.abspath(__file__))
WALLET_NAMES = (("buybacks_wallet", "buybacks.multisignature.near"),
                ("fe_wallet", "fefundsadmin.sputnik-dao.near"),
                ("onecs_wallet", "1csfundsadmin.sputnik-dao.near"))
BEGIN, END = "<!-- BEGIN:RESULTS (generated by run.py, do not edit) -->", "<!-- END:RESULTS -->"


def facts(m):
    w, st, th, ck = m["windows"], m["staking"], m["thesis"], m["checks"]
    d90, d365, d30 = w["d90"], w["d365"], w["d30"]
    pct, usd, near = claims.pct, claims.usd, claims.near
    return {
        "as_of": m["as_of"],
        "epochs": f"{ck['epochs_in_ledger']:,}",
        "first_epoch_date": ck["first_epoch_date"],
        "issuance_rate": pct(d90["issuance_rate"]),
        "issuance_rate_365": pct(d365["issuance_rate"]),
        "minted_90": near(d90["minted_near"]),
        "burnt_90": near(d90["burnt_near"]),
        "issuance_usd_day": usd(d90["issuance_usd_per_day"]),
        "issuance_usd_year": usd(d90["issuance_usd_per_day"] * 365.25),
        "burn_cover": pct(d90["burn_cover"]),
        "burn_multiple": f"{1 / d90['burn_cover']:,.0f}" if d90["burn_cover"] else "n/a",
        "burn_share_of_fees": pct(d90["burn_share_of_gas_fees"], 1),
        "buyback_cover": pct(d90["buyback_cover"], 1),
        "buyback_cover_30": pct(d30["buyback_cover"], 1),
        "gross_fee_cover": pct(d90["gross_fee_cover"], 0),
        "total_cover": pct(d90["total_cover"], 1),
        "net_dilution": pct(th["net_dilution_rate_90d"]),
        "volume_day": usd(d90["intents_volume_usd_per_day"]),
        "volume_yoy": pct(th["intents_volume_growth_yoy"], 0),
        "volume_qoq": pct(th["intents_volume_growth_qoq"], 0),
        "volume_yoy_change": claims._change(th["intents_volume_growth_yoy"]),
        "volume_qoq_change": claims._change(th["intents_volume_growth_qoq"]),
        "gross_fee_rate": pct(d90["gross_fee_rate"], 3),
        "capture_rate": pct(d90["capture_rate"], 3),
        "fees_90": usd(d90["intents_fees_usd"]),
        "revenue_90": usd(d90["intents_revenue_usd"]),
        "buyback_90": usd(d90["intents_holders_revenue_usd"]),
        "buyback_year": usd(d90["intents_holders_revenue_usd"] / 90 * 365.25),
        "breakeven_volume": usd(th["breakeven_volume_usd_per_day"]),
        "breakeven_multiple": f"{th['breakeven_multiple']:.1f}",
        "breakeven_price": usd(th["breakeven_price_usd"]),
        "years_at_yoy": _years(th["years_to_breakeven_at_yoy"]),
        "years_at_half_yoy": _years(th["years_to_breakeven_at_half_yoy"]),
        "price": usd(th["price_usd"]),
        "market_cap": usd(th["market_cap_usd"]),
        "supply": near(th["supply_near"]),
        "mcap_to_buyback": f"{th['mcap_to_annualised_buyback']:.0f}",
        "mcap_to_gross_fees": f"{th['mcap_to_annualised_gross_fees']:.0f}",
        "staked_share": pct(st["staked_share"], 1),
        "staker_apr": pct(st["realized_staker_apr_90d"]),
        "gross_staker_apr": pct(st["gross_staker_apr"]),
        "real_staker_yield": pct(st.get("real_staker_yield_90d")),
        "validators": str(st["validators"]),
        "nakamoto": str(st["nakamoto_33"]),
        "top10_share": pct(st["top10_share"], 1),
        "txns_day": f"{d90['txns_per_day']:,.0f}",
        "accounts_day": f"{d90['active_accounts_per_day']:,.0f}",
        "txns_day_365": f"{d365['txns_per_day']:,.0f}",
        "accounts_day_365": f"{d365['active_accounts_per_day']:,.0f}",
        "wallet_start": near((m.get("wallets") or {}).get("start_total_near")),
        "wallet_end": near((m.get("wallets") or {}).get("end_total_near")),
        "wallet_start_date": (m.get("wallets") or {}).get("start_date", "n/a"),
        "wallet_end_date": (m.get("wallets") or {}).get("end_date", "n/a"),
        "wallet_ratio": format((m.get("wallets") or {}).get("rise_over_buyback") or float("nan"), ".2f"),
        "supply_rel_diff": pct(ck["supply_rel_diff"], 4),
        "gas_fee_sources_ratio": f"{ck['gas_fee_sources_ratio']:.2f}" if ck["gas_fee_sources_ratio"] else "n/a",
    }


def _years(y):
    return "n/a" if y is None else ("never" if y == float("inf") else f"{y:.1f}")


def fill(template, values):
    def sub(match):
        key = match.group(1)
        if key not in values:
            raise KeyError(f"template uses unknown fact {{{{{key}}}}}")
        return values[key]
    return re.sub(r"\{\{(\w+)\}\}", sub, template)


def results_block(m, cl, kills):
    f = facts(m)
    lines = [
        f"Data through **{f['as_of']}** (UTC). Ledger: {f['epochs']} epochs from {f['first_epoch_date']}.",
        "",
        "| Measure (90 days unless noted) | Value |",
        "| --- | --- |",
        f"| Issuance, annual rate of supply | {f['issuance_rate']} |",
        f"| Issuance in USD | {f['issuance_usd_day']} a day |",
        f"| Offset by gas burn | {f['burn_cover']} |",
        f"| Offset by Intents buyback | {f['buyback_cover']} |",
        f"| Net dilution borne by holders | {f['net_dilution']} a year |",
        f"| NEAR Intents volume | {f['volume_day']} a day, {f['volume_yoy_change']} a year earlier |",
        f"| Revenue captured, share of volume | {f['capture_rate']} |",
        f"| Break-even Intents volume | {f['breakeven_volume']} a day, {f['breakeven_multiple']}x today |",
        f"| Break-even NEAR price at today's volume | {f['breakeven_price']} (market {f['price']}) |",
        f"| Staked share of supply | {f['staked_share']} |",
        f"| Realised staker yield, after pool fees | {f['staker_apr']} |",
        f"| Staker yield less net supply growth | {f['real_staker_yield']} |",
        "",
        "| Id | Claim | Status |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {c['id']} | {c['claim']} | {'holds' if c['holds'] else 'FAILS'} |" for c in cl]
    lines += ["", "| Id | The thesis is wrong if | Now | Status |", "| --- | --- | --- | --- |"]
    lines += [f"| {k['id']} | {k['criterion']} | {k['now']} | {'TRIPPED' if k['tripped'] else 'not tripped'} |"
              for k in kills]
    return "\n".join(lines)


def results_md(m, cl, kills, manifest):
    pct, usd, near = claims.pct, claims.usd, claims.near
    out = ["# Results", "",
           "Generated by `python run.py`. Do not edit by hand.", "",
           f"Raw data pulled {manifest.get('pulled_at')}.", "",
           results_block(m, cl, kills), "",
           "## Windows", "",
           "| Window | Minted | Burnt | Issuance rate | Burn offset | Buyback offset | Intents volume a day | Capture rate |",
           "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for key, w in m["windows"].items():
        out.append(f"| {w['days']} days to {w['end']} | {near(w['minted_near'])} | {near(w['burnt_near'])} | "
                   f"{pct(w['issuance_rate'])} | {pct(w['burn_cover'])} | {pct(w['buyback_cover'], 1)} | "
                   f"{usd(w['intents_volume_usd_per_day'])} | {pct(w['capture_rate'], 3)} |")
    out += ["", "## By calendar year", "",
            "| Year | Days | Minted | Burnt | Burn offset | Issuance USD | Intents volume | Buyback | Total offset |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for y in m["yearly"]:
        out.append(f"| {y['year']} from {y['first_day'][5:]} | {y['days']} | {near(y['minted_near'])} | {near(y['burnt_near'])} | "
                   f"{pct(y['burn_cover'])} | {usd(y['issuance_usd'])} | {usd(y['intents_volume_usd'])} | "
                   f"{usd(y['intents_holders_revenue_usd'])} | {pct(y['total_cover'], 1)} |")
    ck = m["checks"]
    out += ["", "## Cross-checks", "",
            f"- Epochs in the raw file: {ck['epochs_total']:,}. In the ledger: {ck['epochs_in_ledger']:,}. "
            f"Missing a first block: {ck['epochs_without_first_block']}.",
            f"- Supply from the last header: {near(ck['header_supply_near'])}. NearBlocks supply for the same day: "
            f"{near(ck['nearblocks_supply_near'])}. Relative difference {pct(ck['supply_rel_diff'], 4)}.",
            f"- Sum of minted minus burnt over the ledger: {ck['sum_minted_minus_burnt_near']:,.3f} NEAR. "
            f"Change in header supply over the same epochs: {ck['supply_change_over_ledger_near']:,.3f} NEAR.",
            f"- Gas fees over 90 days: DefiLlama {usd(ck['llama_gas_fees_usd_90d'])}, NearBlocks "
            f"{usd(ck['nearblocks_gas_fees_usd_90d'])}, ratio {ck['gas_fee_sources_ratio']:.2f}."
            if ck["gas_fee_sources_ratio"] else "- Gas fee comparison not available.",
            ]
    wl = m.get("wallets")
    if wl:
        out += ["", "## Revenue accounts on chain", "",
                "revenue.near.org lists three accounts that hold captured NEAR Intents revenue. Their NEAR balance "
                "(liquid plus locked) is read from chain with `view_account` at one block a week.", "",
                f"| Account | {wl['start_date']} (block {wl['start_height']:,}) | "
                f"{wl['end_date']} (block {wl['end_height']:,}) |",
                "| --- | --- | --- |"]
        for col, acct in WALLET_NAMES:
            out.append(f"| `{acct}` | {wl['start_near'][col]:,.0f} NEAR | {wl['end_near'][col]:,.0f} NEAR |")
        out += [f"| Together | {wl['start_total_near']:,.0f} NEAR | {wl['end_total_near']:,.0f} NEAR |", "",
                f"- Rise in the combined balance: {near(wl['balance_rise_near'])}.",
                f"- DefiLlama buyback revenue over the same days: {usd(wl['buyback_usd'])}, which buys "
                f"{near(wl['buyback_near_at_daily_price'])} at each day's price.",
                f"- On-chain rise divided by that figure: {wl['rise_over_buyback']:.2f}. The two are not expected "
                "to match exactly: the accounts can receive, stake or move NEAR for other reasons, and the "
                "buyback need not be executed on the day revenue is booked."]
    out += ["", "## Raw files", "", "| File | Rows | SHA-256 | Source |", "| --- | --- | --- | --- |"]
    for name, info in sorted(manifest.get("files", {}).items()):
        out.append(f"| data/raw/{name} | {info.get('rows', '')} | `{info.get('sha256', '')[:16]}` | {info.get('url', '')} |")
    return "\n".join(out) + "\n"


def write_all(root, m, cl, kills, manifest):
    values = facts(m)
    with open(os.path.join(root, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(results_md(m, cl, kills, manifest))
    with open(os.path.join(HERE, "thesis_template.md"), encoding="utf-8") as fh:
        thesis = fill(fh.read(), values)
    with open(os.path.join(root, "THESIS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(thesis)
    readme = os.path.join(root, "README.md")
    if os.path.exists(readme):
        with open(readme, encoding="utf-8") as fh:
            text = fh.read()
        if BEGIN in text and END in text:
            head, rest = text.split(BEGIN, 1)
            _, tail = rest.split(END, 1)
            text = head + BEGIN + "\n" + results_block(m, cl, kills) + "\n" + END + tail
            with open(readme, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
